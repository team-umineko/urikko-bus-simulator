_ = None


def trips(deps, rows, nos):
    out = []
    for j, (dep, no) in enumerate(zip(deps, nos)):
        t = {"no": no, "dep": dep}
        for f in FARES:
            v = rows[f][j]
            t[f] = v or 0
        t["total"] = sum(t[f] for f in FARES)
        out.append(t)
    return out


